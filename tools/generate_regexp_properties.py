"""Regenerate the exact Unicode aliases permitted by ECMAScript regex syntax.

Inputs are vendored Unicode 17.0 files, protected by their SHA-256 digests.
ECMAScript requires exact case-sensitive aliases, not Unicode loose matching.
Run from the repository root: python tools/generate_regexp_properties.py
"""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data' / 'unicode' / '17.0.0'
BINARY = set('''ASCII_Hex_Digit Alphabetic Bidi_Control Bidi_Mirrored
Case_Ignorable Cased Changes_When_Casefolded Changes_When_Casemapped
Changes_When_Lowercased Changes_When_NFKC_Casefolded Changes_When_Titlecased
Changes_When_Uppercased Dash Default_Ignorable_Code_Point Deprecated Diacritic
Emoji Emoji_Component Emoji_Modifier Emoji_Modifier_Base Emoji_Presentation
Extended_Pictographic Extender Grapheme_Base Grapheme_Extend Hex_Digit
ID_Continue ID_Start Ideographic IDS_Binary_Operator IDS_Trinary_Operator
Join_Control Logical_Order_Exception Lowercase Math Noncharacter_Code_Point
Pattern_Syntax Pattern_White_Space Quotation_Mark Radical Regional_Indicator
Sentence_Terminal Soft_Dotted Terminal_Punctuation Unified_Ideograph Uppercase
Variation_Selector White_Space XID_Continue XID_Start'''.split())


def fields(name):
    data = (DATA / name).read_bytes()
    expected = {
        'PropertyAliases.txt': '4441f573caf952ffece1d7c892e7715bd7136dfc26f96eb6f268bf1e474715fb',
        'PropertyValueAliases.txt': '64e9a5f76f7a1e8b5a47d6a1f9a26522a251208f5276bdfa1559dac7cf2e827a',
    }[name]
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError('Changed Unicode input: ' + name)
    for line in data.decode('utf-8').splitlines():
        line = line.split('#', 1)[0].strip()
        if line:
            yield [value.strip() for value in line.split(';')]


binary = {'ASCII', 'Any', 'Assigned'}
for row in fields('PropertyAliases.txt'):
    if row[1] in BINARY:
        binary.update(row)
categories = set()
scripts = set()
for row in fields('PropertyValueAliases.txt'):
    if row[0] == 'gc':
        categories.update(row[1:])
    elif row[0] == 'sc':
        scripts.update(row[1:])
output = [
    '# Generated by tools/generate_regexp_properties.py; do not edit.',
    '# Unicode 17.0.0, Unicode data license: data/unicode/LICENSE.txt.',
    '# Aliases are exact, as required by ECMAScript 2026.',
]
for name, values in [('BINARY_PROPERTIES', binary), ('GENERAL_CATEGORIES', categories), ('SCRIPTS', scripts)]:
    output.append(name + ' = frozenset(' + repr(tuple(sorted(values))) + ')')
import argparse
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
target = ROOT / 'esprima' / '_regexp_properties.py'
expected = '\n'.join(output) + '\n'
if args.check:
    if target.read_text(encoding='utf-8') != expected:
        raise SystemExit('Generated regex property data is stale')
    print('Regex property source checksums and generated aliases verified')
else:
    target.write_text(expected, encoding='utf-8', newline='\n')

