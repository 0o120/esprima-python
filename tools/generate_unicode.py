"""Regenerate pinned Unicode 17 ECMAScript identifier data without networking.

The same source and interval algorithm are shared with esutils. esprima vendors
its runtime tables to retain its independent, dependency-free parser API.
Run: python tools/generate_unicode.py [--check]
"""
import argparse
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAME = '17.0.0/DerivedCoreProperties.txt'
DIGEST = '24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08'


def boundaries(ranges, extras):
    ranges = sorted(ranges + [(cp, cp) for cp in extras])
    merged = []
    for low, high in ranges:
        if merged and low <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(high, merged[-1][1]))
        else:
            merged.append((low, high))
    return tuple(value for low, high in merged for value in (low, high + 1))


def generate():
    data = (ROOT / 'data' / 'unicode' / NAME).read_bytes()
    if sha256(data).hexdigest() != DIGEST:
        raise ValueError('Unicode identifier source checksum mismatch')
    ranges = {'ID_Start': [], 'ID_Continue': []}
    for line in data.decode('utf-8').splitlines():
        fields = line.split('#', 1)[0].split(';')
        if len(fields) < 2 or fields[1].strip() not in ranges:
            continue
        ends = fields[0].strip().split('..')
        ranges[fields[1].strip()].append((int(ends[0], 16), int(ends[-1], 16)))
    lines = [
        '# Generated by tools/generate_unicode.py; do not edit by hand.',
        '# Unicode data copyright Unicode, Inc.; see data/unicode/LICENSE.txt.',
        '# Intervals are alternating inclusive starts / exclusive ends.',
        'UNICODE_VERSION = "17.0.0"',
        'SOURCE_SHA256 = {' + repr(NAME) + ': ' + repr(DIGEST) + '}',
    ]
    for name, values in [
        ('ID_START', boundaries(ranges['ID_Start'], (0x24, 0x5F))),
        ('ID_CONTINUE', boundaries(ranges['ID_Continue'], (0x24, 0x5F, 0x200C, 0x200D))),
    ]:
        lines.extend(['', name + ' = ('])
        for offset in range(0, len(values), 10):
            lines.append('    ' + ', '.join('0x%X' % cp for cp in values[offset:offset + 10]) + ',')
        lines.append(')')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'esprima' / '_unicode_data.py'
    expected = generate()
    if args.check:
        if target.read_text(encoding='utf-8') != expected:
            raise SystemExit('Generated Unicode data is stale')
        print('Unicode source checksum and generated tables verified')
    else:
        target.write_text(expected, encoding='utf-8', newline='\n')
